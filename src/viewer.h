#ifndef VIEWER_H
#define VIEWER_H

/*
 * Встроенный просмотрщик/редактор. Никаких внешних less/vi/nano.
 *
 * viewer_open(path, editable):
 *   editable = 0 : просмотр. Стрелки/PgUp/PgDn — навигация, q или ESC — выход.
 *   editable = 1 : редактирование. Ввод текста, Enter — новая строка,
 *                  Backspace — удалить символ, ESC — сохранить и выйти.
 *
 * Возвращает 0 при успехе, -1 если файл не открылся.
 *
 * Поддержка UTF-8: файл читается как поток байт, но отрисовка учитывает
 * многобайтные символы (кириллица отображается корректно). Backspace
 * удаляет целый codepoint, а не один байт.
 *
 * Ввод НЕ-ASCII символов с клавиатуры пока не поддерживается (только ASCII).
 */

int viewer_open(const char *path, int editable);

#endif
